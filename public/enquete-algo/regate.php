    foreach ($ville->habitants() as $h) {
        $ok = true;
        foreach ($criteres as $critere) {
            if (!$critere->accepte($h)) {
                $ok = false;
                break;
            }
        }
        if ($ok) {
            $resultat[] = $h;
        }
    }
    return $resultat;
}


